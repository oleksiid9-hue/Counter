# Імпортуємо клас Flask - це "движок", який створює веб-сервер
# render_template - функція для показу HTML-сторінок
# jsonify - перетворює Python-дані (словники) у формат JSON для браузера
# request - об'єкт, що дозволяє отримувати дані від користувача (з запиту)
from flask import Flask, render_template, jsonify, request

# Створюємо екземпляр застосунку Flask.
# __name__ - спеціальна змінна Python, що містить ім'я поточного файлу/модуля.
# Flask використовує її, щоб знати, де шукати файли static/ та templates/
app = Flask(__name__)

# Це наше "сховище" даних у пам'яті комп'ютера (не в базі даних).
# Це звичайний Python-словник з одним ключем "value" і початковим значенням 0.
# Увага: дані зникнуть, якщо перезапустити сервер!
counter = {"value": 0}


# Декоратор @app.route каже Flask: "коли хтось відкриє адресу '/', виклич функцію нижче"
@app.route("/")
def index():
    # Docstring - опис функції у трьох лапках, для документації
    """Головна сторінка"""
    # render_template шукає файл index.html у папці templates/ і повертає його браузеру
    return render_template("index.html")


# Цей маршрут відповідає на GET-запит (запит на отримання даних) за адресою /api/counter
@app.route("/api/counter", methods=["GET"])
def get_counter():
    """Повертає поточне значення лічильника"""
    # jsonify перетворює наш Python-словник counter у формат JSON,
    # який розуміє JavaScript у браузері
    return jsonify(counter)


# Цей маршрут відповідає лише на POST-запит (запит на зміну даних)
@app.route("/api/counter/increment", methods=["POST"])
def increment_counter():
    """Збільшує лічильник на 1"""
    # Беремо значення за ключем "value" і додаємо до нього 1
    counter["value"] += 1
    # Повертаємо оновлений словник назад у форматі JSON
    return jsonify(counter)


# Ще один маршрут, теж лише для POST-запитів
@app.route("/api/counter/reset", methods=["POST"])
def reset_counter():
    """Скидає лічильник"""
    # Присвоюємо значенню "value" знову 0 - тобто скидаємо лічильник
    counter["value"] = 0
    # Повертаємо оновлений (скинутий) стан лічильника
    return jsonify(counter)


# Ця перевірка означає: "виконай код нижче, тільки якщо цей файл запущено напряму"
# (а не імпортовано в інший файл як модуль)
if __name__ == "__main__":
    # Запускаємо вбудований сервер Flask.
    # debug=True - автоматично перезапускає сервер при зміні коду та показує помилки
    # port=5000 - номер порту, за яким буде доступний сайт (http://localhost:5000)
    app.run(debug=True, port=5000)
